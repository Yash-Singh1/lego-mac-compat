static void dump_limits(void){
  for(unsigned i=0;i<sizeof limits/sizeof*limits;i++){
    double v[16]; for(int k=0;k<16;k++) v[k]=NAN;
    while(glGetError()){}
    glGetDoublev(limits[i].pname,v);
    if(glGetError()) continue;
    int n=0; while(n<16&&!isnan(v[n])) ++n;
    printf("LIMIT.0x%04x.%s=",limits[i].pname,limits[i].name);
    for(int k=0;k<n;k++) printf(k?" %.17g":"%.17g",v[k]);
    printf("\n");
  }
}
